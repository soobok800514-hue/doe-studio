# Tab 4: 반응최적화
# ------------------------------------------------------------
with tab5:
    st.header("4단계: 다중 응답 최적화 (Desirability)")
    st.markdown("**메뉴**: 왼쪽 사이드바 → 🎯 반응최적화")

    st.markdown(
        """
        ### 언제 사용하나요?
        - 응답이 **2개 이상**이고, 동시에 만족시켜야 할 때
        - 예: "최대 하중은 3500N 근처, 변위는 최소로" → Target + Minimize
        """
    )

    st.markdown(
        """
        ### Desirability Function 개념
        각 응답의 측정값을 **0~1 사이의 desirability d** 로 변환합니다.

        - **d = 1**: 완전히 만족 ✅
        - **d = 0**: 완전히 불만족 ❌

        그 다음 모든 응답의 d 들을 **기하평균** 으로 묶어 전체 D 계산:
        $$ D = (d_1 \\times d_2 \\times \\dots \\times d_k)^{1/k} $$

        ⚠️ **한 응답이라도 d=0이면 D=0** → 전체 불만족.
        """
    )

    st.markdown(
        """
        ### 응답 유형 3가지
        """
    )

    col1, col2, col3 = st.columns(3)
    with col1:
        st.markdown("**🔼 Maximize (망대)**")
        st.markdown(
            """
            - **L** (하한): 미만은 d=0
            - **T** (목표): 이상은 d=1
            - 예: 강도, 효율
            """
        )
    with col2:
        st.markdown("**🔽 Minimize (망소)**")
        st.markdown(
            """
            - **T** (목표): 이하는 d=1
            - **U** (상한): 초과는 d=0
            - 예: 결함률, 소음
            """
        )
    with col3:
        st.markdown("**🎯 Target (망목)**")
        st.markdown(
            """
            - **L** (하한): 미만은 d=0
            - **T** (목표): d=1
            - **U** (상한): 초과는 d=0
            - 예: 두께 5±0.5mm
            """
        )

    st.markdown(
        """
        ### 가중치 (Weight)
        - 응답마다 중요도가 다르면 weight를 다르게 (기본 1.0)
        - 예: 안전 관련 응답 = 2.0, 미관 관련 = 0.5
        """
    )

    st.markdown(
        """
        ### 형상 모수 (Shape: s, t)
        - **s = 1**: 선형 (기본)
        - **s > 1**: 목표 근처에서만 d 빠르게 상승 → **보수적** (까다로움)
        - **s < 1**: 목표에서 멀어도 d 천천히 떨어짐 → **관대함**
        """
    )

    st.info(
        "💡 처음에는 모든 s = 1로 시작하고, 결과를 보며 조정하세요. "
        "회사 표준 사양서가 있다면 사양 한계 = L/U 로 설정하면 됩니다."
    )

